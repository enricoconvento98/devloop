package main

import (
	"context"
	"encoding/json"
	"flag"
	"fmt"
	"os"
	"strconv"
	"strings"

	"github.com/anthropics/anthropic-sdk-go"

	"github.com/enricoconvento98/devloop/internal/agent"
	"github.com/enricoconvento98/devloop/internal/ghclient"
)

func planCmd(ctx context.Context, args []string) error {
	fs := flag.NewFlagSet("plan", flag.ExitOnError)
	common := addCommon(fs, 60)
	repoDir := fs.String("repo-dir", "", "local checkout the agent may read (recommended)")
	out := fs.String("out", "", "where to write the plan JSON (default plan-<issue>.json)")
	post := fs.Bool("post", false, "also post the plan as a comment on the issue")
	fs.Usage = func() {
		fmt.Fprintln(fs.Output(), "Usage: devloop plan [flags] <owner/repo> <issue-number>")
		fs.PrintDefaults()
	}
	parseFlags(fs, args)
	if fs.NArg() != 2 {
		fs.Usage()
		os.Exit(2)
	}
	repo, err := ghclient.ParseRepo(fs.Arg(0))
	if err != nil {
		return err
	}
	issue, err := strconv.Atoi(fs.Arg(1))
	if err != nil || issue <= 0 {
		return fmt.Errorf("invalid issue number %q", fs.Arg(1))
	}
	gh, err := ghclient.New(repo)
	if err != nil {
		return err
	}

	pf, stats, err := agent.RunPlan(ctx, anthropic.NewClient(), gh, repo, issue, common.options(*repoDir))
	if err != nil {
		return fmt.Errorf("%w (%s)", err, stats)
	}

	if *out == "" {
		*out = fmt.Sprintf("plan-%d.json", issue)
	}
	b, _ := json.MarshalIndent(pf, "", "  ")
	if err := os.WriteFile(*out, append(b, '\n'), 0o644); err != nil {
		return err
	}

	if common.json {
		os.Stdout.Write(append(b, '\n'))
	} else {
		fmt.Println(renderPlan(pf))
		fmt.Printf("\n_%s_\n", stats)
	}
	fmt.Fprintf(os.Stderr, "plan written to %s; next: devloop implement -plan %s -test '<your test command>'\n", *out, *out)

	if *post {
		url, err := gh.CommentOnIssue(ctx, issue, renderPlan(pf)+"\n\n---\n_Generated by devloop (Claude)_")
		if err != nil {
			return err
		}
		fmt.Fprintln(os.Stderr, "posted plan:", url)
	}
	return nil
}

func renderPlan(pf *agent.PlanFile) string {
	p := pf.Plan
	var b strings.Builder
	fmt.Fprintf(&b, "## Plan for #%d — %s\n\n%s\n\n**Approach.** %s\n\n", pf.Issue.Number, pf.Issue.Title, p.Summary, p.Approach)
	for i, s := range p.Steps {
		fmt.Fprintf(&b, "### %d. %s\n", i+1, s.Title)
		if len(s.Files) > 0 {
			fmt.Fprintf(&b, "`%s`\n\n", strings.Join(s.Files, "`, `"))
		}
		fmt.Fprintf(&b, "%s\n\n", s.Details)
	}
	fmt.Fprintf(&b, "**Test plan.** %s\n", p.TestPlan)
	list := func(title string, items []string) {
		if len(items) == 0 {
			return
		}
		fmt.Fprintf(&b, "\n**%s**\n", title)
		for _, it := range items {
			fmt.Fprintf(&b, "- %s\n", it)
		}
	}
	list("Risks", p.Risks)
	list("Open questions", p.OpenQuestions)
	return strings.TrimRight(b.String(), "\n")
}
