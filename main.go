// Command devloop runs Claude-powered agents over the development cycle:
// planning issues, implementing them, and reviewing and triaging PRs.
package main

import (
	"context"
	"encoding/json"
	"errors"
	"flag"
	"fmt"
	"os"
	"os/signal"
	"strconv"
	"time"

	"github.com/anthropics/anthropic-sdk-go"

	"github.com/enricoconvento98/devloop/internal/agent"
	"github.com/enricoconvento98/devloop/internal/ghclient"
)

const usage = `devloop — Claude-powered agents for the development cycle

Usage:
  devloop plan      [flags] <owner/repo> <issue-number>   issue → implementation plan
  devloop implement [flags] -plan <plan.json>            plan → tested commit (→ draft PR)
  devloop review    [flags] <owner/repo> <pr-number>      PR → findings
  devloop triage    [flags] <owner/repo>                  open PRs → priorities

Run "devloop <command> -h" for the flags of a command.

Env: GITHUB_TOKEN, ANTHROPIC_API_KEY (or an "ant auth login" profile).
implement also needs the claude CLI (Claude Code) on PATH.`

func main() {
	if len(os.Args) < 2 {
		fmt.Fprintln(os.Stderr, usage)
		os.Exit(2)
	}
	ctx, stop := signal.NotifyContext(context.Background(), os.Interrupt)
	defer stop()

	var err error
	switch os.Args[1] {
	case "review":
		err = reviewCmd(ctx, os.Args[2:])
	case "triage":
		err = triageCmd(ctx, os.Args[2:])
	case "plan":
		err = planCmd(ctx, os.Args[2:])
	case "implement":
		err = implementCmd(ctx, os.Args[2:])
	case "-h", "--help", "help":
		fmt.Println(usage)
	default:
		err = fmt.Errorf("unknown command %q\n\n%s", os.Args[1], usage)
	}
	if err != nil {
		fmt.Fprintln(os.Stderr, "error:", err)
		os.Exit(1)
	}
}

type commonFlags struct {
	model, effort string
	maxTurns      int
	json, verbose bool
}

func addCommon(fs *flag.FlagSet, defaultTurns int) *commonFlags {
	c := &commonFlags{}
	fs.StringVar(&c.model, "model", "claude-opus-5-5", "Claude model ID")
	fs.StringVar(&c.effort, "effort", "high", "effort: low, medium, high, xhigh or max")
	fs.IntVar(&c.maxTurns, "max-turns", defaultTurns, "maximum agent turns (API calls)")
	fs.BoolVar(&c.json, "json", false, "print the structured result as JSON")
	fs.BoolVar(&c.verbose, "v", false, "log tool calls and agent notes to stderr")
	return c
}

func (c *commonFlags) options(repoDir string) agent.Options {
	return agent.Options{Model: c.model, Effort: c.effort, MaxTurns: c.maxTurns, RepoDir: repoDir, Verbose: c.verbose}
}

func reviewCmd(ctx context.Context, args []string) error {
	fs := flag.NewFlagSet("review", flag.ExitOnError)
	common := addCommon(fs, 40)
	post := fs.Bool("post", false, "post the review on the PR (as COMMENT; never approves or blocks)")
	repoDir := fs.String("repo-dir", "", "local checkout the agent may read for extra context")
	fs.Usage = func() {
		fmt.Fprintln(fs.Output(), "Usage: devloop review [flags] <owner/repo> <pr-number>")
		fs.PrintDefaults()
	}
	fs.Parse(args)
	if fs.NArg() != 2 {
		fs.Usage()
		os.Exit(2)
	}
	repo, err := ghclient.ParseRepo(fs.Arg(0))
	if err != nil {
		return err
	}
	pr, err := strconv.Atoi(fs.Arg(1))
	if err != nil || pr <= 0 {
		return fmt.Errorf("invalid PR number %q", fs.Arg(1))
	}
	gh, err := ghclient.New(repo)
	if err != nil {
		return err
	}

	review, stats, err := agent.RunReview(ctx, anthropic.NewClient(), gh, repo, pr, common.options(*repoDir))
	if err != nil {
		return fmt.Errorf("%w (%s)", err, stats)
	}
	if common.json {
		printJSON(review)
	} else {
		fmt.Println(renderReview(pr, review, review.Findings))
		fmt.Printf("\n_%s_\n", stats)
	}

	if *post {
		return postReview(ctx, gh, pr, review)
	}
	return nil
}

func postReview(ctx context.Context, gh ghclient.API, pr int, review *agent.Review) error {
	detail, err := gh.GetPR(ctx, pr)
	if err != nil {
		return err
	}
	var inline []ghclient.InlineComment
	var general []agent.Finding
	for _, f := range review.Findings {
		if f.Line > 0 {
			inline = append(inline, ghclient.InlineComment{
				Path: f.File, Line: f.Line,
				Body: fmt.Sprintf("%s **%s** (%s)\n\n%s", severityIcon[f.Severity], f.Title, f.Severity, f.Body),
			})
		} else {
			general = append(general, f)
		}
	}
	const sig = "\n\n---\n_Generated by devloop (Claude)_"
	url, err := gh.PostReview(ctx, pr, detail.HeadSHA, renderReview(pr, review, general)+sig, inline)
	if err != nil && len(inline) > 0 {
		// GitHub rejects inline comments on lines outside the diff; fall back to one body.
		fmt.Fprintf(os.Stderr, "inline comments rejected (%v); posting as a single comment\n", err)
		url, err = gh.PostReview(ctx, pr, detail.HeadSHA, renderReview(pr, review, review.Findings)+sig, nil)
	}
	if err != nil {
		return err
	}
	fmt.Fprintln(os.Stderr, "posted review:", url)
	return nil
}

func triageCmd(ctx context.Context, args []string) error {
	fs := flag.NewFlagSet("triage", flag.ExitOnError)
	common := addCommon(fs, 80)
	limit := fs.Int("limit", 30, "maximum number of open PRs to look at")
	staleDays := fs.Int("stale-days", 14, "days without an update before a PR counts as stale")
	fs.Usage = func() {
		fmt.Fprintln(fs.Output(), "Usage: devloop triage [flags] <owner/repo>")
		fs.PrintDefaults()
	}
	fs.Parse(args)
	if fs.NArg() != 1 {
		fs.Usage()
		os.Exit(2)
	}
	repo, err := ghclient.ParseRepo(fs.Arg(0))
	if err != nil {
		return err
	}
	gh, err := ghclient.New(repo)
	if err != nil {
		return err
	}

	task := fmt.Sprintf("Triage up to %d open pull requests in %s. Today is %s; a PR with no update for %d+ days is stale.",
		*limit, repo, time.Now().Format("2006-01-02"), *staleDays)
	items, stats, err := agent.RunTriage(ctx, anthropic.NewClient(), gh, repo, task, common.options(""))
	if err != nil {
		if errors.Is(err, agent.ErrNoResult) {
			return fmt.Errorf("%w; try a larger -max-turns (%s)", err, stats)
		}
		return fmt.Errorf("%w (%s)", err, stats)
	}
	if common.json {
		printJSON(items)
	} else {
		fmt.Println(renderTriage(repo, items))
		fmt.Printf("\n_%s_\n", stats)
	}
	return nil
}

func printJSON(v any) {
	enc := json.NewEncoder(os.Stdout)
	enc.SetIndent("", "  ")
	enc.Encode(v)
}
